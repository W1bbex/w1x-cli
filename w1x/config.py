DEFAULT_CONFIG = {
    "default_model": "qwen3.5:4b",
    "keep_alive_minutes": 30,
    "context_tokens": 8192,
    "stats_enabled": False,
}


def is_first_run() -> bool:
    """Проверяет, настроен ли W1x (создан ли файл config.json)."""
    return not CONFIG_FILE_PATH.exists()


def load_user_config():
    if not CONFIG_FILE_PATH.exists():
        return dict(DEFAULT_CONFIG)
    try:
        data = json.loads(CONFIG_FILE_PATH.read_text(encoding="utf-8"))
        if isinstance(data, dict):
            cfg = dict(DEFAULT_CONFIG)
            cfg.update(data)
            return cfg
    except Exception:
        pass
    return dict(DEFAULT_CONFIG)


def save_user_config(cfg):
    try:
        tmp_path = CONFIG_FILE_PATH.with_suffix(".tmp")
        tmp_path.write_text(
            json.dumps(cfg, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
        tmp_path.replace(CONFIG_FILE_PATH)
    except Exception:
        pass


def get_keep_alive():
    try:
        mins = int(load_user_config().get("keep_alive_minutes", 30))
    except Exception:
        mins = 30
    if mins <= 0:
        return "0"
    return f"{mins}m"


def get_context_tokens():
    try:
        return int(load_user_config().get("context_tokens", 8192))
    except Exception:
        return 8192


def get_max_history_chars():
    return int(get_context_tokens() * 3.5)


